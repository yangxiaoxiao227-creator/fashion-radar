# 太泛的词：会被统计，但报告里不放进"趋势"区块
GENERIC = {"穿搭（泛指）", "大衣（泛指）", "夹克（泛指）"}


def _build():
    import re
    import unicodedata

    entries = []
    for cn, typ, variants in TERMS:
        for v in variants:
            v_norm = unicodedata.normalize("NFKC", v).lower()
            if re.fullmatch(r"[a-z0-9 \-]+", v_norm):
                strict = re.compile(r"(?<![a-z])" + re.escape(v_norm) + r"(?![a-z])")
                # 短英文词（red、tee、cap）连写时太容易误判，宽松模式下也保持严格
                loose = re.compile(re.escape(v_norm.replace(" ", ""))) if len(v_norm) >= 5 else strict
            else:
                strict = loose = re.compile(re.escape(v_norm))
            entries.append((len(v_norm), strict, loose, cn, typ))
    entries.sort(key=lambda e: -e[0])  # 先匹配长词，避免"트렌치코트"又被算成"코트"
    return entries


_ENTRIES = _build()
TYPE_OF = {cn: typ for cn, typ, _ in TERMS}


def match_terms(text: str, loose: bool = False) -> list[str]:
    """返回一段文字里命中的中文词（去重、保持出现顺序）。

    loose=True 用于 TikTok 话题这种单词连写的文字（如 leatherjacket），
    英文词不要求前后是空格。
    """
    import unicodedata

    s = unicodedata.normalize("NFKC", text or "").lower()
    found: list[str] = []
    for _, strict, loose_pat, cn, _typ in _ENTRIES:
        pattern = loose_pat if loose else strict
        def _mask(m):
            if cn not in found:
                found.append(cn)
            return " " * len(m.group(0))
        s = pattern.sub(_mask, s)
    return found
